#!/usr/bin/env node
/**
 * THE LIVE-DB LANE'S EXECUTION LEDGER — the gate that reads it.
 * (Phase 164.9 TESTISOLATION, the ledger round arising from plan 08 and its fix
 * round, for `[164.9-LIVEDB-LANE-EXECUTION-CENSUS]`.)
 *
 * ── WHAT THIS IS FOR ───────────────────────────────────────────────────────
 * `frontend-live-db-lane` is wired BLOCKING and is measured RED: 18 arms of the
 * 49-file live-DB corpus fail against the committed schema-only baseline, and
 * NONE of the 18 is closable by a fixture (the fix round closed all 17 that
 * were). A blocking job that can only be red is a job whose red says nothing,
 * and the two ways out that were rejected — making the aggregator row advisory,
 * and blocking the phase on a production baseline re-dump — are respectively a
 * forbidden closure and someone else's work.
 *
 * So the lane runs in full and its failing set is compared against a DATED,
 * SHRINK-ONLY ledger of the known-bad arms. GREEN means "the failing set is
 * EXACTLY the ledger". Anything else is RED, in BOTH directions:
 *
 *   NEW    an arm failed that the ledger does not carry. A regression, or a
 *          newly-surfaced defect. ⛔ NEVER closed by adding a line: an entry is
 *          added only with the founder decision the ledger header states.
 *   STALE  an arm the ledger carries no longer fails. DELETE the line, in the
 *          commit that made it stop being true. A ledger allowed to hold stale
 *          entries is a control that has quietly stopped controlling.
 *
 * ⛔ SHRINK-ONLY IS A MECHANISM HERE, NOT A SENTENCE HERE. Set equality alone
 *    cannot see the ledger GROW — a new line for a new regression SATISFIES the
 *    comparison. `ENTRY_CEILING` below is the bound that does see it, and the
 *    contract test holds the staleness direction. This paragraph describes a
 *    constant; it is not the constant.
 *
 * ⛔ AND A VERDICT IS ONLY AS GOOD AS ITS MEASUREMENT. Three separate ways this
 *    gate could once print a false green, each now refused by name:
 *      MODULE ERRORS   a module that fails to IMPORT contributes zero arms and
 *                      zero failures while still counting toward `counts.files`.
 *                      Its arms never ran and can never be ledgered.
 *      ARM FLOOR       a file count cannot notice a module that reported itself
 *                      and then contributed nothing; a collected-arm floor can.
 *      STALE ARTIFACT  the artifact is written only at RUN END, so a vitest that
 *                      dies earlier leaves the PREVIOUS run's file in place. The
 *                      run is bound to its artifact by a nonce, and the artifact
 *                      is unlinked before the spawn.
 *
 * ⛔ THIS IS NOT A TOLERANCE ARM, A WRAPPER THAT SWALLOWS AN EXIT CODE, OR A
 *    SKIP. There is no `|| true` anywhere in this file and no path that exits 0
 *    on an unexpected failure. Every test in the corpus still EXECUTES — this
 *    process reads the run's own artifact after the fact and can neither select
 *    nor deselect an arm. The executed count is printed on every run, and a run
 *    that executed nothing is a HARD FAILURE rather than a pass.
 *
 * ── THE RECORD IS FULL-EQUALITY, AND THAT IS DELIBERATE ────────────────────
 * The comparison key is the WHOLE entry — module, kind, signature class, arm —
 * not just (module, arm). An arm that keeps failing for a DIFFERENT measured
 * reason is a different fact about the tree, and the ledger must be re-derived
 * rather than silently keep describing the old one. Both the class and the kind
 * are chosen to be stable under prose edits: the class turns on the matcher
 * shape and the SQLSTATE, never on message wording.
 *
 * ── WHAT IS MEASURED AND WHAT IS JUDGED, SAID PLAINLY ──────────────────────
 * ⭐ The MODULE, the ARM and the SIGNATURE CLASS are MEASURED: they are derived
 *    from a real run's artifact by `classifySignature` below, and the ledger is
 *    GENERATED by that derivation (`--generate`). Nothing in the entry list was
 *    hand-typed.
 * ⚠️ The KIND is a recorded JUDGEMENT, not a measurement, and this file does not
 *    pretend otherwise. It says WHICH ACT CLOSES the entry, and "a baseline
 *    re-dump will close this" is not a thing a test run can observe. `routeKind`
 *    below holds the routing rules, each with the evidence it turns on; two of
 *    the three rules ARE evidence-keyed, and the third is an explicit list of
 *    three arms whose root causes the fix round derived one at a time.
 *
 * ── USAGE ──────────────────────────────────────────────────────────────────
 *   bash scripts/local-stack/run.sh up           # the lane needs a booted stack
 *   npm run test:live-db:ledger                  # run the lane VERBATIM, then check
 *   node scripts/live-db-execution-ledger.mjs --self-test
 *   node scripts/live-db-execution-ledger.mjs --artifact <file>     # check only
 *   node scripts/live-db-execution-ledger.mjs --artifact <file> --generate
 *   node scripts/live-db-execution-ledger.mjs --ledger <file>       # calibration
 *
 * ⛔ `--ledger` exists for CALIBRATION ON A TEMP COPY. Never point it at a
 *    mutated tracked file; never leave a mutated tracked file behind.
 */
