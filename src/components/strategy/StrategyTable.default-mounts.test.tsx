/** `useId` tokens differ with render order across files; pin their SHAPE only. */
function normalise(html: string): string {
  return html.replace(/(_r_[0-9a-z]+_|:r[0-9a-z]+:|«r[0-9a-z]+»)/g, "<useId>");
}

function mountHtml(ui: ReactElement): string {
  const { container, unmount } = render(ui);
  const html = normalise(container.innerHTML);
  unmount();
  return html;
}

function checkMount(key: keyof typeof FIXTURE, ui: ReactElement): void {
  const html = mountHtml(ui);
  // Non-vacuity: a blank render would equal a blank fixture.
  expect(html.length).toBeGreaterThan(1000);
  expect(html).toBe(FIXTURE[key]);
}

