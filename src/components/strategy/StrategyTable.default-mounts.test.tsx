/**
 * Phase 170.7 / Plan 01 — the byte-identity pin for StrategyTable's three
 * existing mounts (D-01's research resolution: "absent `managerRows` means
 * byte-identical output").
 *
 * WHY THIS FILE EXISTS. 170.7 teaches the shared table a manager mode through
 * one optional prop. The table is mounted by three pages that are NOT the
 * manager page: /discovery (signed-in allocator: star column, percentiles),
 * /browse (anonymous: no userId) and /my-strategies (the owner mount:
 * `visibility="owner-all-statuses"`, placeholder rows, ownership and rename
 * callbacks). One of them is anonymous. A class or cell that changes on any of
 * the three because of a manager-mode edit is a public-surface regression, and
 * no existing test would say so: the censuses assert fragments (a td count, a
 * `sticky` literal), never the whole markup.
 *
 * WHAT IT PINS. Each mount's `container.innerHTML`, with React `useId` tokens
 * normalised to a stable placeholder, equals the matching entry of
 * `__fixtures__/strategy-table-default-mounts.json`.
 *
 * ⛔ THE FIXTURE WAS CAPTURED AT THE POST-170.2 HEAD BEFORE ANY 170.7 EDIT to
 * StrategyTable.tsx (merge of origin/main at v0.130.0.0). THIS TEST HAS NO
 * WRITE OR UPDATE PATH, on purpose. A diff here means a public or owner mount
 * changed; the fix is the SOURCE, never a regenerated fixture. A fixture that
 * can be regenerated by the run it guards is not a pin.
 *
 * ONE SURGICAL EDIT, on merging TRADESYNC (167.1.2.2.2 plan 22) with main: the
 * "Synced {age}" badge span (a claim read off computed_at) was REMOVED BY HAND
 * from the fixture's three mounts, ten spans in all, because the badge now
 * states the cron's trade fetch and these rows carry none. Nothing else moved;
 * the fixture was not regenerated.
 *
 * SECOND SURGICAL EDIT, 2026-10-13, 170.6.2 COPYPASS D-06: ` checked=""` was
 * ADDED BY HAND to the "Hide examples" input in the fixture's three mounts
 * (three occurrences in all). The old pin lacked the attribute because the box
 * was created unchecked (`showExamples` started true) and then flipped by an
 * effect, which only moves the DOM property: the missing attribute was the
 * example-row flash itself. With the fix the box is created checked, so React
 * writes the attribute at creation. The visible state is identical: the box
 * reads checked after mount either way. Nothing else moved; the fixture was
 * not regenerated.
 *
 * The clock is frozen (Date only; timers stay real so RTL's async helpers keep
 * working): SyncBadge and the empty-series state derive from `Date.now()`.
 */

